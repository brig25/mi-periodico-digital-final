function open_art(id) {
  const a = arts[id];
  if (!a) return;
  document.getElementById('mImg').src = a.img;
  document.getElementById('mImg').alt = a.title;
  document.getElementById('mCat').textContent = a.cat;
  document.getElementById('mTitle').textContent = a.title;
  document.getElementById('mMeta').textContent = a.meta;
  document.getElementById('mText').innerHTML = a.body;
  const ov = document.getElementById('overlay');
  ov.classList.add('open');
  document.body.style.overflow = 'hidden';
  ov.scrollTop = 0;
}

function close_art() {
  document.getElementById('overlay').classList.remove('open');
  document.body.style.overflow = '';
}

function close_if_out(e) {
  if (e.target === document.getElementById('overlay')) close_art();
}

document.addEventListener('keydown', function(e) {
  if (e.key === 'Escape') close_art();
});

const ham = document.getElementById('hamburger');
const menu = document.getElementById('mobileMenu');

ham.addEventListener('click', function() {
  ham.classList.toggle('open');
  menu.classList.toggle('open');
  document.body.style.overflow = menu.classList.contains('open') ? 'hidden' : '';
});

document.getElementById('mobileClose').addEventListener('click', function() {
  ham.classList.remove('open');
  menu.classList.remove('open');
  document.body.style.overflow = '';
});

document.querySelectorAll('.mob-link').forEach(function(a) {
  a.addEventListener('click', function() {
    ham.classList.remove('open');
    menu.classList.remove('open');
    document.body.style.overflow = '';
  });
});

function checkNav() {
  var isMobile = window.innerWidth < 768;
  document.getElementById('navLinks').style.display = isMobile ? 'none' : 'flex';
  ham.style.display = isMobile ? 'flex' : 'none';
}

checkNav();
window.addEventListener('resize', checkNav);

var sections = document.querySelectorAll('[id]');
var navLinks = document.querySelectorAll('nav a');

sections.forEach(function(sec) {
  new IntersectionObserver(function(entries) {
    entries.forEach(function(e) {
      if (e.isIntersecting) {
        navLinks.forEach(function(a) { a.classList.remove('active'); });
        var link = document.querySelector('nav a[href="#' + sec.id + '"]');
        if (link) link.classList.add('active');
      }
    });
  }, { threshold: 0.3 }).observe(sec);
});